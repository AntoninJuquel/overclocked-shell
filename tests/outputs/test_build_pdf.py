def substitute_sheet():
    s = resolved_sheet()
    s["intent"]["weapons"] = [
        {"slot": "Kinetic", "role": "add clear", "items": ["DECATUR 02"],
         "perks": [["Physic", "Attrition Orbs"], ["Reciprocity"]],
         "mods": ["Ballistics"], "masterworks": ["Masterworked: Range"]},
        {"slot": "Power", "role": "boss DPS", "type": "Machine Gun", "items": ["Song of Ir Yut"]},
        {"slot": "Energy", "role": "roam", "type": "Sniper Rifle", "perks": [["Repulsor Brace"]]},
    ]
    s["resolved"]["weapons"].append({"slot": "Power", "itemId": "8", "name": "Corrective Measure", "why": "Stand-in.",
                                     "mod": "Backup Mag", "perks": ["Killing Tally"]})
    s["resolved"]["rationale"] += ["Gap: Song of Ir Yut not owned.", "Écart : DECATUR 02 en Extended Barrel."]
    return s


def test_shows_the_intent_not_the_inventory(icons, tmp_path):
    icons["item:Getaway Artist"] = tmp_path / "ga.png"
    icons["item:Getaway Artist"].write_bytes(PNG)
    data, warnings = build_pdf.render(substitute_sheet(), icons, fonts=None, compress=False,
                                      armor={"Gauntlets": "Getaway Artist"})
    for shown in (b"Song of Ir Yut", b"Sniper Rifle"):
        assert shown in data, shown
    for hidden in (b"Corrective Measure", b"Stand-in", b"Gap:", b"Extended Barrel", b"(171)", b"EXOTIC", b"Add clear.",
                   b"Feed the Void heals", b"Arc grenades on a loop", b"WHY IT WORKS"):
        assert hidden not in data, hidden
    for icon_key in ("perk:Attrition Orbs", "perk:Ballistics", "perk:Masterworked: Range"):   # alternatives included
        assert f"no icon: {icon_key}" in warnings
    assert not any("Grenade Mod" in w or "Backup Mag" in w or "Killing Tally" in w for w in warnings)


